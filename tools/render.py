# Video
# ----------------------------------------------------------------------------

def shot_filter(shot: dict, w: int, h: int, fps: float) -> str:
    vertical = h > w
    if shot["camera"] == "insta" and shot.get("v360"):
        v = shot["v360"]
        if vertical:
            v_fov = v["fov"]
            h_fov = v_fov * w / h
        else:
            h_fov = v["fov"]
            v_fov = h_fov * h / w
        vf = (f"v360=input=e:output=flat:yaw={v['yaw']}:pitch={v['pitch']}:roll=0:"
              f"h_fov={h_fov:.2f}:v_fov={v_fov:.2f}:w={w}:h={h}:interp=lanczos")
    elif vertical:
        vf = f"crop=ih*{w}/{h}:ih,scale={w}:{h}"
    else:
        vf = f"scale={w}:{h}:force_original_aspect_ratio=decrease,pad={w}:{h}:(ow-iw)/2:(oh-ih)/2"
    return f"{vf},fps={fps_str(fps)},format=yuv420p"


def render_clip(shot: dict, out: Path, w: int, h: int, fps: float) -> None:
    args = ["-ss", f"{shot['source_in']:.3f}", "-t", f"{shot['duration']:.3f}", "-i", shot["source"],
            "-vf", shot_filter(shot, w, h, fps), "-an"]
    try:
        encode_with_fallback([*cuda_decode_args(), *args], out, fps)
    except RuntimeError:
        if cuda_decode_args():
            encode_with_fallback(args, out, fps)  # CPU decode fallback
        else:
            raise


def render_video_track(segments: list[dict], clip_dir: Path, w: int, h: int, fps: float, label: str) -> Path:
    clip_dir.mkdir(parents=True, exist_ok=True)
    listing = []
    for i, shot in enumerate(segments):
        clip = clip_dir / f"seg_{i:03d}.mp4"
        if not clip.exists() or clip.stat().st_size == 0:
            render_clip(shot, clip, w, h, fps)
        listing.append(f"file '{clip.name}'")
        if i % 10 == 9:
            log(f"  {label}: {i+1}/{len(segments)} shots rendered")
    concat = clip_dir / "concat.txt"
    concat.write_text("\n".join(listing) + "\n", encoding="utf-8")
    out = clip_dir / "video_only.mp4"
    ffmpeg(["-f", "concat", "-safe", "0", "-i", "concat.txt", "-c", "copy", out.name], cwd=str(clip_dir))
    return out



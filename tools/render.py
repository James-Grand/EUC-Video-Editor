"""
render.py - Steps 10 and 11. Turn edit_plan.json into finished video files.

Plain-language summary:
  For the long video and for each short:
  1. Render every shot in the plan to its own small clip (GPU decode, v360
     reframe for 360 footage, scale/crop, NVENC GPU encode, no audio).
  2. Join the clips with ffmpeg's concat (no re-encode, so it's fast).
  3. Build the three audio layers on the OUTPUT timeline:
       voice   - slices of voice_clean.wav matching each shot
       ambient - slices of the GoPro track, aligned using sync.json, low level,
                 louder in speed sections where nobody's talking
       music   - generated by make_music.py; chill or speed per section
  4. Mix: music ducks under voice (sidechaincompress), everything summed,
     then loudnorm to -14 LUFS / -1 dBTP (YouTube's target).
  5. Mux video + audio. Shorts also get word-group captions burned in.
  6. Write long.srt (transcript re-timed to the finished video).

Run:  python tools/render.py <ride-id> [long|short_01|all]
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

import numpy as np
import soundfile as sf

from common import (CONFIG, FFMPEG, cuda_decode_args, ffmpeg, fmt_time, free_space_gb, log, output_dir,
                    read_json, run, run_log, run_log_header, srt_time, work_dir, write_json)
import make_music

FPS_RATIONAL = {23.976: "24000/1001", 29.97: "30000/1001", 59.94: "60000/1001"}

# Set to True the first time NVENC refuses to start; we then use the CPU
# encoder (libx264) for the rest of the run and note it in the log.
_NVENC_BROKEN = {"flag": False, "reason": ""}


def fps_str(fps: float) -> str:
    return FPS_RATIONAL.get(fps, str(fps))


def encoder_args(fps: float) -> list[str]:
    r = CONFIG["render"]
    if _NVENC_BROKEN["flag"] or "nvenc" not in r["video_codec"]:
        return ["-c:v", "libx264", "-preset", "fast", "-crf", "20",
                "-g", str(int(round(fps * 2))), "-pix_fmt", "yuv420p"]
    return ["-c:v", r["video_codec"], "-preset", r["nvenc_preset"], "-rc", "vbr", "-cq", str(r["nvenc_cq"]),
            "-b:v", "0", "-g", str(int(round(fps * 2))), "-pix_fmt", "yuv420p"]


def encode_with_fallback(args_before_encoder: list[str], out: Path, fps: float, cwd=None) -> None:
    """Run ffmpeg with the GPU encoder; if the GPU encoder itself fails, redo on CPU."""
    try:
        ffmpeg([*args_before_encoder, *encoder_args(fps), str(out)], cwd=cwd)
    except RuntimeError as e:
        msg = str(e)
        if "nvenc" in msg.lower() and not _NVENC_BROKEN["flag"]:
            _NVENC_BROKEN["flag"] = True
            lines = [ln for ln in msg.splitlines() if "nvenc" in ln.lower() and "driver" in ln.lower()]
            _NVENC_BROKEN["reason"] = (lines or msg.strip().splitlines()[-1:] or ["unknown"])[0].strip()[:200]
            log("WARNING: NVENC GPU encoder failed; switching to CPU encoder (libx264) for this run. "
                f"Reason: {_NVENC_BROKEN['reason']}")
            ffmpeg([*args_before_encoder, *encoder_args(fps), str(out)], cwd=cwd)
        else:
            raise



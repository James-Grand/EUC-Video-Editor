def read_slice(path: Path, start_s: float, dur_s: float, sr: int) -> np.ndarray:
    """Read part of a WAV. Pads with silence if the slice runs past the ends."""
    n = int(round(dur_s * sr))
    out = np.zeros(n, dtype=np.float32)
    if not path.exists():
        return out
    with sf.SoundFile(str(path)) as f:
        total = len(f)
        a = int(round(start_s * sr))
        b = a + n
        ra, rb = max(0, a), min(total, b)
        if rb > ra:
            f.seek(ra)
            data = f.read(rb - ra, dtype="float32", always_2d=False)
            if data.ndim > 1:
                data = data.mean(axis=1)
            out[ra - a: ra - a + len(data)] = data
    return out


def fade_edges(x: np.ndarray, sr: int, ms: float = 12) -> np.ndarray:
    n = min(len(x) // 2, int(sr * ms / 1000))
    if n > 0:
        ramp = np.linspace(0, 1, n, dtype=np.float32)
        x[:n] *= ramp
        x[-n:] *= ramp[::-1]
    return x


def is_speed(shot: dict) -> bool:
    return any("speed" in r for r in shot["reasons"])


def talking_during(islands: list[dict], t0: float, t1: float) -> bool:
    return any(i["start"] < t1 and i["end"] > t0 for i in islands)


def build_audio(segments: list[dict], wd: Path, out_dir: Path, islands: list[dict]) -> dict:
    cfg = CONFIG["audio"]
    sr = cfg["sample_rate"]
    sync = read_json(wd / "sync.json")
    lag = sync.get("ambient_lag_s", 0.0)
    adir = wd / "audio"
    voice_parts, amb_parts, sections = [], [], []
    for shot in segments:
        t0, t1, d = shot["timeline_in"], shot["timeline_out"], shot["duration"]
        voice_parts.append(fade_edges(read_slice(adir / "voice_clean.wav", t0, d, sr), sr))
        gain_db = cfg["ambient_gain_db"]
        if is_speed(shot) and not talking_during(islands, t0, t1):
            gain_db += cfg["ambient_speed_boost_db"]
        amb = read_slice(adir / "ambient.wav", t0 + lag, d, sr) * (10 ** (gain_db / 20))
        amb_parts.append(fade_edges(amb, sr))
        mood = "speed" if is_speed(shot) else "chill"
        if sections and sections[-1]["mood"] == mood:
            sections[-1]["duration"] += d
        else:
            sections.append({"mood": mood, "duration": d})

    # Music sections shorter than 8 s just flicker; fold them into a neighbour.
    merged = []
    for s in sections:
        if merged and (s["duration"] < 8 or merged[-1]["duration"] < 8):
            merged[-1]["duration"] += s["duration"]
        else:
            merged.append(dict(s))
    sections = merged or [{"mood": "chill", "duration": sum(s["duration"] for s in segments)}]

    voice = np.concatenate(voice_parts) if voice_parts else np.zeros(1, np.float32)
    amb = np.concatenate(amb_parts) if amb_parts else np.zeros(1, np.float32)
    sf.write(str(out_dir / "voice_cut.wav"), voice, sr, subtype="PCM_16")
    sf.write(str(out_dir / "ambient_cut.wav"), amb, sr, subtype="PCM_16")
    make_music.render_bed(sections, out_dir / "music.wav")
    return {"sections": sections, "duration": len(voice) / sr}


def mix_and_mux(video: Path, out_dir: Path, final: Path, captions: Path | None, fps: float) -> None:
    cfg = CONFIG["audio"]
    r = CONFIG["render"]
    graph = (
        f"[1:a]aformat=channel_layouts=stereo,asplit[vA][vB];"
        f"[2:a]volume={cfg['music_gain_db']}dB[m];"
        f"[m][vB]sidechaincompress=threshold=0.015:ratio=6:attack=25:release=500:makeup=1[md];"
        f"[3:a]aformat=channel_layouts=stereo[amb];"
        f"[vA][md][amb]amix=inputs=3:normalize=0:duration=first:dropout_transition=0[mix];"
        f"[mix]loudnorm=I={cfg['target_lufs']}:TP={cfg['target_true_peak']}:LRA=11[aout]"
    )
    args = ["-i", str(video), "-i", str(out_dir / "voice_cut.wav"), "-i", str(out_dir / "music.wav"),
            "-i", str(out_dir / "ambient_cut.wav"), "-filter_complex", graph,
            "-map", "0:v", "-map", "[aout]", "-c:a", "aac", "-b:a", r["audio_bitrate"], "-shortest"]
    if captions:
        style = ("FontName=Arial,FontSize=22,Bold=1,PrimaryColour=&H00FFFFFF,OutlineColour=&H00000000,"
                 "BackColour=&H80000000,BorderStyle=1,Outline=3,Shadow=0,Alignment=2,MarginV=70")
        args += ["-vf", f"subtitles={captions.name}:force_style='{style}'"]
        encode_with_fallback(args, final, fps, cwd=str(captions.parent))
    else:
        ffmpeg([*args, "-c:v", "copy", "-movflags", "+faststart", str(final)])


# ----------------------------------------------------------------------------
# Captions / subtitles re-timed to the output
# ----------------------------------------------------------------------------

def ride_to_out(segments: list[dict], t: float) -> float | None:
    for s in segments:
        if s["timeline_in"] <= t <= s["timeline_out"]:
            return s["out_in"] + (t - s["timeline_in"])
    return None


def long_srt(segments: list[dict], transcript: dict, path: Path) -> int:
    lines, n = [], 0
    for seg in transcript.get("segments", []):
        words = seg.get("words") or []
        if not words:
            continue
        # Keep only the words that made it into the video; split on cuts.
        groups, cur = [], []
        for wd_ in words:
            o = ride_to_out(segments, (wd_["start"] + wd_["end"]) / 2)
            if o is None:
                if cur:
                    groups.append(cur)
                cur = []
                continue
            if cur and o - cur[-1][1] > 1.5:
                groups.append(cur)
                cur = []
            cur.append((o - (wd_["end"] - wd_["start"]) / 2, o + (wd_["end"] - wd_["start"]) / 2, wd_["word"]))
        if cur:
            groups.append(cur)
        for g in groups:
            n += 1
            lines += [str(n), f"{srt_time(g[0][0])} --> {srt_time(g[-1][1] + 0.2)}",
                      "".join(x[2] for x in g).strip(), ""]
    path.write_text("\n".join(lines), encoding="utf-8")
    return n


def short_captions(segments: list[dict], transcript: dict, path: Path, max_words: int = 4, max_s: float = 2.2) -> int:
    lines, n, group = [], 0, []

    def flush():
        nonlocal n, group
        if group:
            n += 1
            lines.extend([str(n), f"{srt_time(group[0][0])} --> {srt_time(group[-1][1])}",
                          " ".join(x[2] for x in group).upper(), ""])
            group = []

    for wd_ in transcript.get("words", []):
        o = ride_to_out(segments, (wd_["start"] + wd_["end"]) / 2)
        if o is None:
            flush()
            continue
        half = (wd_["end"] - wd_["start"]) / 2
        if group and (len(group) >= max_words or o + half - group[0][0] > max_s or o - half - group[-1][1] > 0.8):
            flush()
        group.append((o - half, o + half + 0.15, wd_["word"].strip()))
    flush()
    path.write_text("\n".join(lines), encoding="utf-8")
    return n



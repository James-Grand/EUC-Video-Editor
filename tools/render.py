def render_one(ride_id: str, plan: dict, which: str) -> Path | None:
    r = CONFIG["render"]
    wd = work_dir(ride_id)
    transcript = read_json(wd / "transcript.json", {"segments": [], "words": [], "speech_islands": []})
    islands = transcript.get("speech_islands", [])
    fps = plan["fps"]

    if which == "long":
        segments = plan["long"]["segments"]
        w, h = r["long_width"], r["long_height"]
        captions = None
    else:
        short = next((s for s in plan["shorts"] if s["id"] == which), None)
        if not short:
            return None
        segments = short["segments"]
        w, h = r["short_width"], r["short_height"]
    if not segments:
        run_log(ride_id, f"{which}: no segments, skipped")
        return None

    rdir = wd / "render" / which
    rdir.mkdir(parents=True, exist_ok=True)
    log(f"{which}: rendering {len(segments)} shots at {w}x{h} {fps}fps")
    video = render_video_track(segments, rdir / "clips", w, h, fps, which)
    audio_info = build_audio(segments, wd, rdir, islands)

    final = output_dir(ride_id) / f"{which}.mp4"
    if which == "long":
        n = long_srt(segments, transcript, output_dir(ride_id) / "long.srt")
        run_log(ride_id, f"long.srt: {n} caption lines")
        mix_and_mux(video, rdir, final, None, fps)
    else:
        cap = rdir / "captions.srt"
        n = short_captions(segments, transcript, cap)
        mix_and_mux(video, rdir, final, cap if n else None, fps)
    run_log(ride_id, f"{which}.mp4 written: {fmt_time(audio_info['duration'])}, music sections "
                     f"{[f'{s['mood']} {s['duration']:.0f}s' for s in audio_info['sections']]}")
    if _NVENC_BROKEN["flag"]:
        run_log(ride_id, f"WARNING: rendered with CPU encoder (libx264) because NVENC failed: {_NVENC_BROKEN['reason']}")
    return final


def main(ride_id: str, which: str = "all") -> list[Path]:
    wd = work_dir(ride_id)
    plan = read_json(wd / "edit_plan.json")
    if not plan:
        raise SystemExit("no edit_plan.json; run edit_plan.py first")
    run_log_header(ride_id, "Render")
    free = free_space_gb()
    if free < 10:
        run_log(ride_id, f"WARNING: only {free:.1f} GB free on disk")
    targets = ["long"] + [s["id"] for s in plan["shorts"]] if which == "all" else [which]
    outs = []
    for t in targets:
        p = render_one(ride_id, plan, t)
        if p:
            outs.append(p)
    # Temp clips can be several GB; clear them once the finals exist.
    shutil.rmtree(wd / "render", ignore_errors=True)
    shutil.rmtree(wd / "tmp", ignore_errors=True)
    return outs


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit("usage: render.py <ride-id> [long|short_01|all]")
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else "all")
